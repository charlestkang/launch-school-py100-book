# EXERCISE 1
# If you have a list named people, how can you determine the number of entries in that list?

# len(people) returns the number of entries in the list. You could also manually iterate
# and count the items with a for loop but that would be unnecessary. 

# Ex: 
people = [1, 2, 3, 4, 5, 6, 7]
len_people = len(people)
print(len_people)
